# ---------- دانت ----------
def teeth():
    W, H = 900, 470
    b = [text(450, 26, "دانتوں کے نام: ایک جبڑے کی ۱۶ دانتوں کی قطار (نچلے جبڑے میں بھی یہی ترتیب)", "dg-t")]
    # وسط سے دائیں طرف: ثنیہ، رباعیہ، ناب، ضاحک، طاحن×3، ناجذ  (چوڑائی، رنگ، نام)
    half = [(40, "g", "ثنایا"), (36, "g", "رباعیات"), (44, "y", "انیاب"), (46, "b", "ضواحک"), (60, "b", "طواحن"), (60, "b", "طواحن"), (60, "b", "طواحن"), (56, "r", "نواجذ")]
    colv = {"g": "var(--green)", "y": "var(--gold)", "b": "var(--blue)", "r": "var(--red)"}
    gap = 6
    def layout(side):
        x = 450 + side*gap/2
        res = []
        for w, c, n in half:
            if side > 0:
                res.append((x, w, c, n)); x += w + gap
            else:
                res.append((x - w, w, c, n)); x -= w + gap
        return res
    ty = 120
    for side in (1, -1):
        for x, w, c, n in layout(side):
            h = 90 if c in ("g", "y") else 80
            b.append(f'<rect class="dg-tooth" x="{x}" y="{ty}" width="{w}" height="{h}" rx="14" style="stroke:{colv[c]};stroke-width:3"/>')
    # بریکٹس (دائیں طرف کی تفصیل؛ بائیں آئینہ)
    groups = [("ثنایا", [0], "g", "۱"), ("رباعیات", [1], "g", "۱"), ("انیاب", [2], "y", "۱"), ("ضواحک", [3], "b", "۱"), ("طواحن", [4, 5, 6], "b", "۳"), ("نواجذ", [7], "r", "۱")]
    for side in (1, -1):
        L = layout(side)
        for gi, (name, idx, c, cnt) in enumerate(groups):
            xs = [L[i][0] for i in idx] + [L[i][0] + L[i][1] for i in idx]
            x0, x1 = min(xs), max(xs)
            yb = 232 + (gi % 2) * 70
            b.append(f'<path class="dg-line" d="M{x0+3} {yb-14} L{x0+3} {yb} L{x1-3} {yb} L{x1-3} {yb-14}" style="stroke:{colv[c]}"/>')
            b.append(text((x0+x1)/2, yb+22, name, "dg-t"))
            b.append(text((x0+x1)/2, yb+42, f"{cnt}", "dg-s"))
    b.append(text(450, 90, "وسط (درمیانی لکیر)", "dg-s"))
    b.append(f'<line class="dg-lead" x1="450" y1="104" x2="450" y2="215" stroke-dasharray="4 4"/>')
    b.append(text(450, 392, "ہر نام کے نیچے تعداد: ایک جبڑے کی ایک جانب میں؛ دونوں جانب اور دونوں جبڑوں میں چار گنا (طواحن: ۱۲)۔", "dg-s"))
    b.append(text(450, 420, "کل ۳۲ دانت: ثنایا ۴ + رباعیات ۴ + انیاب ۴ + ضواحک ۴ + طواحن ۱۲ + نواجذ ۴", "dg-s"))
    b.append(text(450, 446, "ضواحک + طواحن + نواجذ = ۲۰ ڈاڑھیں (اضراس)", "dg-s"))
    write("teeth", svg(W, H, "".join(b), "دانتوں کے نام"))
teeth()
